#Introdução da atividade:
#Cria um algoritimo que solicite ao usuário um número e conte até 10
#Variáveis utilizadas: number

number = int(input("Informe um número: ")) # Solicita ao usuário um número

for i in range(number): # Número informado pelo usuário será a quantidade e o (i) irá exibir essa quantidade

    i += 1 # O (i) começa como 0, faremos este contador para que ele comece como 1

    print(i) # Exibe uma lista com as quantidades dos número informado
