#Introdução da atividade:
#Cria um algoritimo que solicita entrada de dois números informados pelo usuário.
#Variáveis utilizadas: number1 e number2

number1 = int(input("Informe o número 1: "))
number2 = int(input("Informe o número 2: "))

soma = number1 + number2
mult = number1 * number2
subt = number1 - number2
divs = number1 / number2


print("\n|Soma dos números:          ", soma  ,"    |")
print("|Multiplicação dos números: ", mult  ,"    |")
print("|Subtração dos números:     ", subt  ,"    |")
print("|Divisão dos números:     ",   divs  ,"    |\n")
